function ending(word) {
  const n = word.id.length + word.word.length
  const options = [
    `If you can make one new sentence with “${word.word}” without looking it up, you know more than a translation.`,
    `Try saying “${word.word}” out loud in the example, then swap in your own details — that is how it sticks.`,
    `Do not only recognise “${word.word}” on a list. Use it once today, even in a short message.`,
    `A useful test: can you explain “${word.word}” to a friend in simple English? If yes, you own it.`,
  ]
  return options[n % options.length]
}

export function defaultExplainer(word) {
  const pos = POS_LINE[word.pos] || `used as a ${word.pos}`
  const level = LEVEL_LINE[word.level] || ''
  return [
    `“${word.word}” is ${pos}. In clear English: ${word.meaning}`,
    level,
    `A tight way to remember it: ${word.hint}`,
    `You will hear it in sentences such as: “${word.example}”`,
    ending(word),
  ]
    .filter(Boolean)
    .join(' ')
}

export function buildLesson(word, related = []) {
  const extra = ALL_LESSONS[word.id] || {}
  const examples = [word.example, ...(extra.extraExamples || word.extraExamples || [])].filter(Boolean)
  const uniqueExamples = [...new Set(examples)]

  return {
    explainer: extra.explainer || word.explainer || defaultExplainer(word),
    examples: uniqueExamples,
    note: extra.note || word.note || '',
    synonyms: extra.synonyms || word.synonyms || [],
    related: related.map((item) => ({
      id: item.id,
      word: item.word,
      pos: item.pos,
      level: item.level,
      meaning: item.meaning,
    })),
  }
}
